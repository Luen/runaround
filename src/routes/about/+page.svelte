<h1>About RunAround</h1>
<p>
	RunAround is a Townsville-based running website that aims to promote running in our community,
	inspire others to get outdoors, and stay connected with like-minded people. The Townsville Virtual
	Running Series is the brainchild of
	<a href="/about/sidney-willis">Sidney Willis</a> from
	<a href="https://www.hungryrunner.net/">Hungry Runner Coaching</a>. This virtual running series
	allows participants the flexibility that conventional races can't offer.
</p>
<p>
	Our goal is to give Townsville runners the opportunity to regularly test themselves on different
	running courses. Races are either <strong>Road</strong> or <strong>Trail</strong>. Some are flat,
	others hilly. We hope this challenges runners on terrains they are more or less adapted to.
</p>
<h2>How to enter</h2>
<p>
	Connect your Strava account, add an email for notifications, and run a published course. We match
	your GPS trace to the route. During a race window your best time counts for that race. The overall
	leaderboard stays open so you can come back later and try to beat the record.
</p>
